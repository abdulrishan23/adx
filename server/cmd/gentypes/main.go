// Command gentypes writes the TypeScript types the web app uses to talk to
// the API. A Go struct reaches TypeScript only if it has json tags, so
// handles like projects.Projects stay out. Run it from server/ with
// `make gen`.
package main

import (
	"fmt"
	"go/types"
	"os"
	"reflect"
	"strings"

	"github.com/coder/guts"
	"github.com/coder/guts/config"
	"golang.org/x/tools/go/packages"
)

var sources = []string{"./api", "./core/..."}

const out = "../web/src/api/types.gen.ts"

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gentypes:", err)
		os.Exit(1)
	}
}

func run() error {
	parser, err := guts.NewGolangParser()
	if err != nil {
		return err
	}
	for _, src := range sources {
		if err := parser.IncludeGenerate(src); err != nil {
			return err
		}
	}
	parser.IncludeCustomDeclaration(config.StandardMappings())

	skip, err := typesWithoutJSON(sources)
	if err != nil {
		return err
	}
	if err := parser.ExcludeCustom(skip...); err != nil {
		return err
	}

	ts, err := parser.ToTypescript()
	if err != nil {
		return err
	}
	ts.ApplyMutations(config.EnumAsTypes, config.ExportTypes)
	body, err := ts.Serialize()
	if err != nil {
		return err
	}
	body = strings.TrimPrefix(body, "// Code generated by 'guts'. DO NOT EDIT.\n\n")
	header := "// Code generated by server/cmd/gentypes. DO NOT EDIT.\n\n"
	return os.WriteFile(out, []byte(header+body), 0o644)
}

// typesWithoutJSON lists exported structs with no json tags, plus interfaces
// and func types. None of them cross the wire.
func typesWithoutJSON(patterns []string) ([]string, error) {
	pkgs, err := packages.Load(&packages.Config{Mode: packages.NeedTypes | packages.NeedName}, patterns...)
	if err != nil {
		return nil, err
	}
	var skip []string
	for _, pkg := range pkgs {
		scope := pkg.Types.Scope()
		for _, name := range scope.Names() {
			tn, ok := scope.Lookup(name).(*types.TypeName)
			if !ok || !tn.Exported() {
				continue
			}
			switch u := tn.Type().Underlying().(type) {
			case *types.Struct:
				if !hasJSONTag(u) {
					skip = append(skip, tn.Type().String())
				}
			case *types.Interface, *types.Signature:
				skip = append(skip, tn.Type().String())
			}
		}
	}
	return skip, nil
}

func hasJSONTag(s *types.Struct) bool {
	for i := range s.NumFields() {
		if _, ok := reflect.StructTag(s.Tag(i)).Lookup("json"); ok {
			return true
		}
	}
	return false
}
