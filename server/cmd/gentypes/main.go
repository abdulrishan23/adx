// Command gentypes writes the TypeScript types the web app uses to talk to
// the API. A Go struct reaches TypeScript only if it has json tags, so
// handles like projects.Projects stay out. Run it from server/ with
// `make gen`.
package main

import (
	"fmt"
	"go/types"
	"os"
	"reflect"
	"slices"
	"sort"
	"strings"

	"github.com/coder/guts"
	"github.com/coder/guts/config"
	"golang.org/x/tools/go/packages"
)

var sources = []string{"./api", "./core/..."}

const out = "../web/src/api/types.gen.ts"

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gentypes:", err)
		os.Exit(1)
	}
}

func run() error {
	parser, err := guts.NewGolangParser()
	if err != nil {
		return err
	}
	for _, src := range sources {
		if err := parser.IncludeGenerate(src); err != nil {
			return err
		}
	}
	parser.IncludeCustomDeclaration(config.StandardMappings())

	skip, shared, err := typesWithoutJSON(sources)
	if err != nil {
		return err
	}
	if err := parser.ExcludeCustom(skip...); err != nil {
		return err
	}

	ts, err := parser.ToTypescript()
	if err != nil {
		return err
	}
	ts.ApplyMutations(config.EnumAsTypes, config.ExportTypes)
	body, err := ts.Serialize()
	if err != nil {
		return err
	}
	body = strings.TrimPrefix(body, "// Code generated by 'guts'. DO NOT EDIT.\n\n")
	body = settleShared(body, shared)
	header := "// Code generated by server/cmd/gentypes. DO NOT EDIT.\n\n"
	return os.WriteFile(out, []byte(header+body), 0o644)
}

// settleShared makes the output the same on every run for a type name that
// two packages declare (runs.Completeness and evidence.Completeness, say).
// guts folds them into one union by iterating a map, so the member order and
// the "From" line flip between runs and the CI check that generated code is
// committed fails at random. Members are sorted without repeats and the
// comment names every package.
func settleShared(body string, shared map[string][]string) string {
	lines := strings.Split(body, "\n")
	for i, line := range lines {
		name, members, ok := unionLine(line)
		if !ok || shared[name] == nil {
			continue
		}
		sort.Strings(members)
		members = slices.Compact(members)
		lines[i] = "export type " + name + " = " + strings.Join(members, " | ") + ";"
		if i > 0 && strings.HasPrefix(lines[i-1], "// From ") {
			lines[i-1] = "// From " + strings.Join(shared[name], ", ")
		}
	}
	return strings.Join(lines, "\n")
}

// unionLine reads `export type Name = "a" | "b";`.
func unionLine(line string) (string, []string, bool) {
	rest, ok := strings.CutPrefix(line, "export type ")
	if !ok {
		return "", nil, false
	}
	name, rhs, ok := strings.Cut(rest, " = ")
	rhs, closed := strings.CutSuffix(rhs, ";")
	if !ok || !closed || !strings.HasPrefix(rhs, "\"") {
		return "", nil, false
	}
	return name, strings.Split(rhs, " | "), true
}

// typesWithoutJSON lists exported structs with no json tags, plus interfaces
// and func types. None of them cross the wire. It also reports every
// exported type name declared by more than one package, with the packages
// in order, for settleShared.
func typesWithoutJSON(patterns []string) ([]string, map[string][]string, error) {
	pkgs, err := packages.Load(&packages.Config{Mode: packages.NeedTypes | packages.NeedName}, patterns...)
	if err != nil {
		return nil, nil, err
	}
	var skip []string
	declared := map[string][]string{}
	for _, pkg := range pkgs {
		scope := pkg.Types.Scope()
		for _, name := range scope.Names() {
			tn, ok := scope.Lookup(name).(*types.TypeName)
			if !ok || !tn.Exported() {
				continue
			}
			declared[name] = append(declared[name], pkg.Name)
			switch u := tn.Type().Underlying().(type) {
			case *types.Struct:
				if !hasJSONTag(u) {
					skip = append(skip, tn.Type().String())
				}
			case *types.Interface, *types.Signature:
				skip = append(skip, tn.Type().String())
			}
		}
	}
	shared := map[string][]string{}
	for name, in := range declared {
		if len(in) > 1 {
			sort.Strings(in)
			shared[name] = in
		}
	}
	return skip, shared, nil
}

func hasJSONTag(s *types.Struct) bool {
	for i := range s.NumFields() {
		if _, ok := reflect.StructTag(s.Tag(i)).Lookup("json"); ok {
			return true
		}
	}
	return false
}
